-- ─────────────────────────────────────────────────────────────
-- 3. TAX FILINGS
-- Stores GST filing records — when filed, by whom, for which month
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.tax_filings (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    month_key       TEXT NOT NULL UNIQUE,          -- e.g. '2026-07' (YYYY-MM)
    month_label     TEXT NOT NULL,                 -- e.g. 'July 2026'
    cgst_amount     NUMERIC(12,2) DEFAULT 0,
    sgst_amount     NUMERIC(12,2) DEFAULT 0,
    net_payable     NUMERIC(12,2) DEFAULT 0,
    taxable_margin  NUMERIC(12,2) DEFAULT 0,
    status          TEXT DEFAULT 'due' CHECK (status IN ('due', 'filed', 'overdue')),
    filed_at        TIMESTAMPTZ,
    filed_by        UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    filed_by_name   TEXT,                          -- snapshot of name at filing time
    reference_no    TEXT,                          -- GST filing reference number
    notes           TEXT,
    created_at      TIMESTAMPTZ DEFAULT now(),
    updated_at      TIMESTAMPTZ DEFAULT now()
);

