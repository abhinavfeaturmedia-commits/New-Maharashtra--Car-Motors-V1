-- ─────────────────────────────────────────────────────────────
-- 1. MESSAGE TEMPLATES
-- Stores WhatsApp / SMS / Email communication templates
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.message_templates (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name         TEXT NOT NULL,
    category     TEXT NOT NULL DEFAULT 'whatsapp' CHECK (category IN ('whatsapp', 'sms', 'email')),
    subject      TEXT,                              -- for email only
    body         TEXT NOT NULL,
    variables    TEXT[] DEFAULT '{}',              -- e.g. {customer_name}, {car_model}
    is_active    BOOLEAN DEFAULT true,
    usage_count  INT DEFAULT 0,
    created_by   UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at   TIMESTAMPTZ DEFAULT now(),
    updated_at   TIMESTAMPTZ DEFAULT now()
);

ALTER TABLE public.message_templates ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admins manage message_templates" ON public.message_templates;
CREATE POLICY "Admins manage message_templates"
    ON public.message_templates FOR ALL
    USING (public.is_admin());
DROP POLICY IF EXISTS "Staff read message_templates" ON public.message_templates;
CREATE POLICY "Staff read message_templates"
    ON public.message_templates FOR SELECT
    TO authenticated USING (true);

-- ─────────────────────────────────────────────────────────────
-- 2. MANUAL TRANSACTIONS
-- Allows admins to log custom income/expense entries (petty cash, rent, misc)
-- These appear in the Accounts ledger alongside auto-derived entries
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.manual_transactions (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    description  TEXT NOT NULL,
    type         TEXT NOT NULL CHECK (type IN ('income', 'expense')),
    amount       NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    mode         TEXT DEFAULT 'Cash' CHECK (mode IN ('Cash', 'Bank Transfer', 'UPI', 'Cheque', 'Card', 'Other')),
    category     TEXT DEFAULT 'General',
    notes        TEXT,
    status       TEXT DEFAULT 'Completed' CHECK (status IN ('Completed', 'Pending')),
    transaction_date DATE DEFAULT CURRENT_DATE,
    created_by   UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at   TIMESTAMPTZ DEFAULT now(),
    updated_at   TIMESTAMPTZ DEFAULT now()
);

ALTER TABLE public.manual_transactions ENABLE ROW LEVEL SECURITY;
